#!/usr/bin/env node
/**
 * Starts the isolated test Postgres on 127.0.0.1:55432.
 * Refuses to run if Docker is missing. Does not touch BuilMate.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const backendRoot = path.resolve(__dirname, '../..');
const repoRoot = path.resolve(backendRoot, '..');
const composeFile = path.join(repoRoot, 'docker-compose.test.yml');
const envDocker = path.join(backendRoot, '.env.test.docker');
const envTest = path.join(backendRoot, '.env.test');

function dockerAvailable() {
  const probe = spawnSync('docker', ['version'], { encoding: 'utf8' });
  return probe.status === 0;
}

function loadDockerEnv() {
  if (!fs.existsSync(envDocker)) return {};
  const out = {};
  for (const line of fs.readFileSync(envDocker, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) out[match[1]] = match[2];
  }
  return out;
}

function main() {
  if (!dockerAvailable()) {
    console.error(`Docker is not available on this machine.

BuildMate cannot create BuilMate_test until one of these is true:

1) Install Docker Desktop, then from the BUILDMATE folder run:
     npm run test:db:up --prefix backend
     npm run test:db:bootstrap --prefix backend
     npm test --prefix backend

2) Or, if you know the local PostgreSQL 18 superuser password, create
   gitignored backend/.env.test.admin with:
     TEST_PGHOST=127.0.0.1
     TEST_PGPORT=5432
     TEST_PGUSER=postgres
     TEST_PGPASSWORD=<local superuser password>
   then:
     node scripts/bootstrap-isolated-test-db.js

Do not point TEST_DATABASE_URL at the team database BuilMate.
Do not install Docker from this script.`);
    process.exit(2);
  }

  let env = loadDockerEnv();
  if (!env.TEST_PGPASSWORD) {
    env = {
      TEST_PGHOST: '127.0.0.1',
      TEST_PGPORT: '55432',
      TEST_PGUSER: 'buildmate_test',
      TEST_PGPASSWORD: crypto.randomBytes(12).toString('base64url'),
      POSTGRES_DB: 'BuilMate_test',
    };
    const lines = Object.entries(env).map(([key, value]) => `${key}=${value}`).join('\n');
    fs.writeFileSync(envDocker, `# gitignored local test secrets\n${lines}\n`);
  }

  const up = spawnSync(
    'docker',
    ['compose', '-f', composeFile, '--env-file', envDocker, 'up', '-d', '--wait'],
    { cwd: repoRoot, stdio: 'inherit', env: { ...process.env, ...env } }
  );
  if (up.status !== 0) process.exit(up.status || 1);

  const user = encodeURIComponent(env.TEST_PGUSER || 'buildmate_test');
  const password = encodeURIComponent(env.TEST_PGPASSWORD);
  const url = `postgresql://${user}:${password}@127.0.0.1:55432/BuilMate_test`;
  fs.writeFileSync(
    envTest,
    `# Generated by scripts/test-db/up.js. Do not commit.\nNODE_ENV=test\nTEST_DATABASE_URL=${url}\n`
  );
  console.log('[test-db] Wrote backend/.env.test (gitignored). Listening on 127.0.0.1:55432 / BuilMate_test.');
}

main();
